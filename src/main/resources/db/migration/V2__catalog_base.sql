-- 应用目录只描述可售能力，不保存地理、商圈或真实商家资料。
CREATE TABLE application_category (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(64) NOT NULL,
  icon VARCHAR(255) NOT NULL DEFAULT '',
  sort INT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_application_category_name (name),
  KEY idx_application_category_sort (sort, id),
  CONSTRAINT chk_application_category_sort CHECK (sort >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 评分、评论数、销量和价格下限由服务端维护，请求只能读取。
CREATE TABLE ai_application (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  category_id BIGINT UNSIGNED NOT NULL,
  owner_user_id BIGINT UNSIGNED NULL,
  name VARCHAR(128) NOT NULL,
  summary VARCHAR(255) NOT NULL,
  description TEXT NOT NULL,
  capabilities VARCHAR(512) NOT NULL DEFAULT '',
  cover_url VARCHAR(512) NOT NULL DEFAULT '',
  model_name VARCHAR(64) NOT NULL DEFAULT '',
  model_version VARCHAR(64) NOT NULL DEFAULT '',
  application_version INT UNSIGNED NOT NULL DEFAULT 1,
  price_from BIGINT UNSIGNED NOT NULL DEFAULT 0,
  score INT UNSIGNED NOT NULL DEFAULT 0,
  review_count INT UNSIGNED NOT NULL DEFAULT 0,
  sold_count INT UNSIGNED NOT NULL DEFAULT 0,
  status TINYINT UNSIGNED NOT NULL DEFAULT 1,
  published_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_ai_application_name (name),
  KEY idx_ai_application_category (category_id, status, score, id),
  KEY idx_ai_application_price (status, price_from, id),
  KEY idx_ai_application_published (status, published_at, id),
  CONSTRAINT fk_ai_application_category FOREIGN KEY (category_id)
    REFERENCES application_category (id),
  CONSTRAINT fk_ai_application_owner FOREIGN KEY (owner_user_id) REFERENCES creator_user (id),
  CONSTRAINT chk_ai_application_score CHECK (score <= 50),
  CONSTRAINT chk_ai_application_status CHECK (status IN (1, 2)),
  CONSTRAINT chk_ai_application_version CHECK (application_version > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 使用包保存稳定元数据；可售状态与锁量活动不进入缓存判断。
CREATE TABLE usage_product (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  application_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(128) NOT NULL,
  subtitle VARCHAR(255) NOT NULL DEFAULT '',
  rules VARCHAR(1024) NOT NULL DEFAULT '',
  price BIGINT UNSIGNED NOT NULL,
  credits INT UNSIGNED NOT NULL,
  valid_days INT UNSIGNED NOT NULL,
  sale_mode TINYINT UNSIGNED NOT NULL DEFAULT 0,
  application_version INT UNSIGNED NOT NULL,
  model_version VARCHAR(64) NOT NULL DEFAULT '',
  image_size VARCHAR(32) NOT NULL DEFAULT '',
  output_count INT UNSIGNED NOT NULL DEFAULT 1,
  status TINYINT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_usage_product_application (application_id, status, id),
  CONSTRAINT fk_usage_product_application FOREIGN KEY (application_id)
    REFERENCES ai_application (id),
  CONSTRAINT chk_usage_product_credits CHECK (credits > 0),
  CONSTRAINT chk_usage_product_valid_days CHECK (valid_days > 0),
  CONSTRAINT chk_usage_product_sale_mode CHECK (sale_mode IN (0, 1)),
  CONSTRAINT chk_usage_product_output CHECK (output_count > 0),
  CONSTRAINT chk_usage_product_status CHECK (status IN (1, 2))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

